// Vitest setup file
// Import extend expect with jest-dom matchers
import '@testing-library/jest-dom';
// Create a jest shim for backward compatibility with Vitest
import { vi } from 'vitest';

// Make jest available globally as an alias for vi
(window as any).jest = vi;

// Mock localStorage for tests
const localStorageMock = (() => {
  let store: Record<string, string> = {};
  return {
    getItem: (key: string) => store[key] || null,
    setItem: (key: string, value: string) => {
      store[key] = value;
    },
    removeItem: (key: string) => {
      delete store[key];
    },
    clear: () => {
      store = {};
    },
  };
})();

Object.defineProperty(window, 'localStorage', {
  value: localStorageMock,
});

// jsdom does not implement ResizeObserver, which recharts' ResponsiveContainer
// (used by the Stats page) relies on. Provide a no-op stub so chart components
// mount under test.
class ResizeObserverStub {
  observe() {}
  unobserve() {}
  disconnect() {}
}
(globalThis as unknown as { ResizeObserver: typeof ResizeObserverStub }).ResizeObserver =
  ResizeObserverStub;

// jsdom does not implement matchMedia (used by MUI + recharts in some paths).
if (!window.matchMedia) {
  Object.defineProperty(window, 'matchMedia', {
    writable: true,
    value: (query: string) => ({
      matches: false,
      media: query,
      onchange: null,
      addListener: () => {},
      removeListener: () => {},
      addEventListener: () => {},
      removeEventListener: () => {},
      dispatchEvent: () => {},
    }),
  });
}
